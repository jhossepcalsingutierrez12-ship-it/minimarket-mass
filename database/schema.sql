DELIMITER $$

-- R7: solo se vende con una sesión de caja abierta
CREATE TRIGGER TRG_VENTA_SESION_ABIERTA
BEFORE INSERT ON VENTA
FOR EACH ROW
BEGIN
  DECLARE v_estado VARCHAR(8);
  SELECT ESTADO INTO v_estado FROM SESION_CAJA WHERE ID_SESION = NEW.ID_SESION;
  IF v_estado <> 'ABIERTA' THEN
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = 'R7: la sesion de caja esta cerrada. No se puede vender.';
  END IF;
END$$

-- R4: las ventas no se borran, se anulan
CREATE TRIGGER TRG_VENTA_NO_BORRAR
BEFORE DELETE ON VENTA
FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000'
    SET MESSAGE_TEXT = 'R4: las ventas no se borran. Use UPDATE VENTA SET ESTADO = ''ANULADA''.';
END$$

-- R4: una venta anulada no vuelve a quedar emitida
CREATE TRIGGER TRG_VENTA_ESTADO
BEFORE UPDATE ON VENTA
FOR EACH ROW
BEGIN
  IF OLD.ESTADO = 'ANULADA' AND NEW.ESTADO <> 'ANULADA' THEN
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = 'R4: una venta anulada no puede volver a emitirse.';
  END IF;
END$$

-- R5: cada línea vendida descuenta el stock
CREATE TRIGGER TRG_DETALLE_DESCUENTA_STOCK
AFTER INSERT ON DETALLE_VENTA
FOR EACH ROW
BEGIN
  UPDATE INVENTARIO SET STOCK_ACTUAL = STOCK_ACTUAL - NEW.CANTIDAD
   WHERE ID_PRODUCTO = NEW.ID_PRODUCTO;
  IF ROW_COUNT() = 0 THEN
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = 'R5: el producto no tiene inventario.';
  END IF;
END$$

-- R4 + R5: al anular una venta, el stock vuelve al inventario
CREATE TRIGGER TRG_VENTA_ANULA_STOCK
AFTER UPDATE ON VENTA
FOR EACH ROW
BEGIN
  IF OLD.ESTADO = 'EMITIDA' AND NEW.ESTADO = 'ANULADA' THEN
    UPDATE INVENTARIO i
      JOIN DETALLE_VENTA d ON d.ID_PRODUCTO = i.ID_PRODUCTO
       SET i.STOCK_ACTUAL = i.STOCK_ACTUAL + d.CANTIDAD
     WHERE d.ID_VENTA = NEW.ID_VENTA;
  END IF;
END$$

-- Merma: lo que se pierde también sale del inventario
CREATE TRIGGER TRG_MERMA_DESCUENTA_STOCK
AFTER INSERT ON MERMA
FOR EACH ROW
BEGIN
  UPDATE INVENTARIO SET STOCK_ACTUAL = STOCK_ACTUAL - NEW.CANTIDAD
   WHERE ID_PRODUCTO = NEW.ID_PRODUCTO;
END$$

